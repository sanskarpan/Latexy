def test_legacy_deploy_version_resolution_rejects_dirty_and_normalizes_git_refs(tmp_path):
    """Build tags must be exact release tags or full clean commit SHAs."""
    script = _read("scripts/deploy/deploy.sh")
    function = script.split("get_current_version() {", 1)[1].split("\n}\n", 1)[0]
    wrapper = f'''\
log() {{ printf '%s\\n' "$*" >&2; }}
get_current_version() {{
{function}
}}
get_current_version
'''

    def git(*args: str) -> None:
        subprocess.run(["git", *args], cwd=tmp_path, check=True, capture_output=True)

    git("init", "-q")
    git("config", "user.email", "test@example.invalid")
    git("config", "user.name", "Deploy Test")
    (tmp_path / "tracked").write_text("one\n")
    git("add", "tracked")
    git("commit", "-qm", "initial")
    git("tag", "v1.2.3")

    exact = subprocess.run(["bash", "-c", wrapper], cwd=tmp_path, text=True, capture_output=True, check=True)
    assert exact.stdout.strip() == "v1.2.3"

    (tmp_path / "tracked").write_text("two\n")
    git("add", "tracked")
    git("commit", "-qm", "ahead")
    ahead = subprocess.run(["bash", "-c", wrapper], cwd=tmp_path, text=True, capture_output=True, check=True)
    assert ahead.stdout.strip() == f"sha-{subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=tmp_path, text=True).strip()}"

    (tmp_path / "tracked").write_text("dirty\n")
    dirty = subprocess.run(["bash", "-c", wrapper], cwd=tmp_path, text=True, capture_output=True, check=False)
    assert dirty.returncode != 0
