import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]

BACKEND_PORT = "8030"
FRONTEND_PORT = "5180"


def _read(relative: str) -> str:
    return (REPO_ROOT / relative).read_text()


def _load_all(relative: str) -> list:
    return [doc for doc in yaml.safe_load_all(_read(relative)) if doc]


def _k8s_manifests() -> list:
    docs = []
    for path in sorted((REPO_ROOT / "k8s").rglob("*.yaml")):
        docs.extend(doc for doc in yaml.safe_load_all(path.read_text()) if doc)
    return docs


def _containers(doc: dict) -> list:
    if doc.get("kind") != "Deployment":
        return []
    return doc["spec"]["template"]["spec"]["containers"]


def _env_names(container: dict) -> set:
    return {entry["name"] for entry in container.get("env", [])}


def _requirement_names(relative: str) -> set[str]:
    def normalize(name: str) -> str:
        return re.sub(r"[-_.]+", "-", name.lower())

    names: set[str] = set()
    for raw in _read(relative).splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("-"):
            continue
        match = re.match(r"([A-Za-z0-9][A-Za-z0-9_.-]*)", line)
        if match:
            names.add(normalize(match.group(1)))
    return names


def _locked_names(relative: str) -> set[str]:
    def normalize(name: str) -> str:
        return re.sub(r"[-_.]+", "-", name.lower())

    return {
        normalize(match.group(1))
        for match in re.finditer(r"^([A-Za-z0-9][A-Za-z0-9_.-]*)==", _read(relative), re.MULTILINE)
    }


def _pinned_requirements(relative: str) -> dict[str, str]:
    def normalize(name: str) -> str:
        return re.sub(r"[-_.]+", "-", name.lower())

    pinned: dict[str, str] = {}
    for raw in _read(relative).splitlines():
        line = raw.strip()
        match = re.match(r"([A-Za-z0-9][A-Za-z0-9_.-]*)==([^\s;]+)", line)
        if match:
            pinned[normalize(match.group(1))] = match.group(2)
    return pinned


