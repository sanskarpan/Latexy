def test_python_lock_inputs_are_hash_verified_and_cover_every_direct_dependency():
    """Human-edited requirements must never silently outrun generated locks."""
    production = _read("backend/requirements.lock")
    development = _read("backend/requirements-dev.lock")
    for lock in (production, development):
        assert "--hash=sha256:" in lock
        assert "# This file was autogenerated by uv" in lock
        assert "-r requirements.txt" not in lock.splitlines()[:4]
    prod_names = _requirement_names("backend/requirements.txt")
    dev_names = _requirement_names("backend/requirements-dev.txt") | prod_names
    assert prod_names <= _locked_names("backend/requirements.lock")
    assert dev_names <= _locked_names("backend/requirements-dev.lock")
    locked_versions = {
        re.sub(r"[-_.]+", "-", match.group(1).lower()): match.group(2)
        for match in re.finditer(
            r"^([A-Za-z0-9][A-Za-z0-9_.-]*)==([^\s]+)", production, re.MULTILINE
        )
    }
    assert _pinned_requirements("backend/requirements.txt") == {
        name: locked_versions[name] for name in _pinned_requirements("backend/requirements.txt")
    }

    for relative in ("backend/Dockerfile", "backend/Dockerfile.prod"):
        dockerfile = _read(relative)
        assert "requirements.lock" in dockerfile or "requirements-dev.lock" in dockerfile
        assert "pip install --no-cache-dir -r requirements.txt" not in dockerfile
    modal = _read("backend/modal_app.py")
    assert modal.count('pip_install_from_requirements("requirements.lock"') == 4
    assert modal.count('extra_options="--require-hashes"') == 4
    assert 'python_version="3.12"' in modal

    ci = _read(".github/workflows/ci.yml")
    assert "uv pip install -r requirements-dev.txt" not in ci
    assert ci.count("uv pip sync --require-hashes --verify-hashes requirements-dev.lock") == 4
    assert "uv pip compile --python-version 3.12 --generate-hashes" in ci
    assert "--custom-compile-command" in ci
    assert 'diff -u requirements.lock "$lock_tmp/requirements.lock"' in ci
    assert 'diff -u requirements-dev.lock "$lock_tmp/requirements-dev.lock"' in ci
    assert "pip install -r requirements.txt" not in _read("backend/setup.sh")
    assert "requirements-dev.lock" in _read("docker-compose.test.yml")


