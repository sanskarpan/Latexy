import { test } from 'node:test'
import assert from 'node:assert/strict'
import { createServer } from 'node:http'
import { once } from 'node:events'
import { PassThrough } from 'node:stream'
import { createPwaAcceptanceProxy, localUpstream, versionedWorker } from './pwa-acceptance-server.mjs'
import { verifyPwaReport, EXPECTED_PWA_TITLES } from './pwa-acceptance.mjs'

async function listen(server) {
  server.listen(0, '127.0.0.1')
  await once(server, 'listening')
  return `http://127.0.0.1:${server.address().port}`
}
async function close(server) {
  server.closeAllConnections()
  await new Promise(resolve => server.close(resolve))
}

test('fixture proxy rejects external or credential-bearing upstreams', () => {
  for (const invalid of ['https://localhost:3000', 'http://example.invalid:3000',
    'http://user:password@127.0.0.1:3000', 'http://127.0.0.1:3000/private', 'http://localhost:3000/?token=secret']) {
    assert.throws(() => localUpstream(invalid), /loopback/)
  }
  assert.equal(localUpstream('http://127.0.0.1:3000').origin, 'http://127.0.0.1:3000')
})

test('request targets cannot replace the validated loopback destination', async () => {
  for (const upstream of ['http://127.0.0.1:3000', 'http://localhost:5194']) {
    for (const target of [
      '/a/..//remote.invalid/probe',
      'http://localhost//remote.invalid/probe',
      '//remote.invalid/probe',
      'http://remote.invalid:8080/probe?mode=post',
      'http://user:password@remote.invalid/probe',
      '/a/%2e%2e//remote.invalid/probe?mode=post',
      '/a/..//127.0.0.1:1/probe',
      '/sw.js?version=2',
    ]) {
      const headers = { host: 'remote.invalid', 'content-type': 'application/json', 'x-test': 'preserved', 'accept-encoding': 'gzip' }
      let options
      let timeout
      let body = ''
      const outgoing = new PassThrough()
      outgoing.setTimeout = milliseconds => { timeout = milliseconds }
      outgoing.on('data', chunk => { body += chunk.toString() })
      // Exercise the actual HTTP request listener without opening any sockets.
      // Capture the same options passed to node:http in normal proxy operation.
      const proxy = createPwaAcceptanceProxy(upstream, actualOptions => {
        options = actualOptions
        return outgoing
      })
      const incoming = Object.assign(new PassThrough(), { url: target, method: 'POST', headers })
      const response = { writeHead() { assert.fail('Unexpected fixture interception') } }
      const finished = once(outgoing, 'finish')
      proxy.emit('request', incoming, response)
      incoming.end('{"synthetic":"post body"}')
      await finished
      const expected = new URL(upstream)
      const request = new URL(target, 'http://localhost')
      assert.equal(options.protocol, expected.protocol)
      assert.equal(options.hostname, expected.hostname)
      assert.equal(options.port, expected.port)
      assert.equal(options.path, request.pathname + request.search)
      assert.equal(options.method, 'POST')
      assert.equal(options.headers.host, expected.host)
      assert.equal(options.headers['content-type'], 'application/json')
      assert.equal(options.headers['x-test'], 'preserved')
      assert.equal(headers.host, 'remote.invalid')
      assert.equal(options.headers['accept-encoding'], request.pathname === '/sw.js' ? undefined : 'gzip')
      assert.equal(timeout, 30_000)
      assert.equal(body, '{"synthetic":"post body"}')
    }
  }
  assert.throws(() => createPwaAcceptanceProxy('http://remote.invalid:3000'), /loopback/)
})

test('worker updates derive only comments from unchanged generated bytes', async () => {
  const original = 'self.addEventListener("fetch", () => {});'
  const upstream = createServer((request, response) => {
    response.writeHead(200, { 'Content-Type': 'application/javascript', 'ETag': 'unchanged' })
    response.end(original)
  })
  const origin = await listen(upstream)
  const proxy = createPwaAcceptanceProxy(origin)
  const base = await listen(proxy)
  try {
    const first = await fetch(`${base}/sw.js`).catch(error => {
      throw new Error(`Local fixture response failed: ${error.cause?.code ?? error.name}: ${error.cause?.message ?? ''}`)
    })
    assert.equal(first.headers.get('etag'), null)
    assert.equal(await first.text(), original)
    const before = await fetch(`${base}/__pwa_acceptance__/worker-version`).then(r => r.json())
    await fetch(`${base}/__pwa_acceptance__/worker-version`, { method: 'POST' })
    assert.match(await fetch(`${base}/sw.js`).then(r => r.text()), /version 2/)
    const after = await fetch(`${base}/__pwa_acceptance__/worker-version`).then(r => r.json())
    assert.equal(after.workerIdentity.originalSha256, before.workerIdentity.originalSha256)
    assert.notEqual(after.workerIdentity.derivedSha256, before.workerIdentity.derivedSha256)
    const denied = await fetch(`${base}/api/pwa-acceptance/private`)
    assert.equal(denied.status, 401)
    const allowed = await fetch(`${base}/api/pwa-acceptance/private`, { headers: { 'X-Test-Owner': 'beta' } })
    assert.equal(allowed.headers.get('cache-control'), 'private, no-store')
    assert.equal((await allowed.json()).owner, 'beta')
  } finally { await close(proxy); await close(upstream) }
})

test('worker derivation keeps source immutable and emits consistent uncompressed response headers', () => {
  const original = Buffer.from('self.addEventListener("fetch", () => {});')
  const headers = { etag: 'old', 'last-modified': 'old', 'transfer-encoding': 'chunked', 'content-type': 'application/javascript' }
  const first = versionedWorker(original, headers, 1)
  const second = versionedWorker(original, headers, 2)
  assert.equal(first.identity.originalSha256, second.identity.originalSha256)
  assert.notEqual(first.identity.derivedSha256, second.identity.derivedSha256)
  assert.equal(first.body.subarray(0, original.length).equals(original), true)
  assert.equal(first.identity.originalSha256, first.identity.derivedSha256)
  assert.equal(first.headers['content-length'], first.body.length)
  assert.equal(first.headers['transfer-encoding'], undefined)
  assert.equal(first.headers.etag, undefined)
  assert.equal(headers.etag, 'old')
})

function successfulReport() {
  const files = ['pwa-production.spec.ts', 'pwa-worker-lifecycle.spec.ts', 'offline-compiled-pdf.spec.ts']
  return { stats: { expected: 12, unexpected: 0, skipped: 0, flaky: 0 }, errors: [],
    suites: [{ specs: Array.from({ length: 12 }, (_, index) => ({ file: files[index === 0 ? 0 : index < 3 ? 1 : 2], title: EXPECTED_PWA_TITLES[index], ok: true,
      tests: [{ projectName: 'chromium-pwa', expectedStatus: 'passed', results: [{ status: 'passed' }] }] })) }] }
}

test('explicit PWA selection fails closed on zero, skipped, incomplete or wrong-scope evidence', () => {
  assert.equal(verifyPwaReport(successfulReport()).passed, 12)
  for (const mutate of [
    report => { report.stats.expected = 0 },
    report => { report.stats.skipped = 1 },
    report => { report.stats.flaky = 1 },
    report => { report.suites[0].specs.pop() },
    report => { report.suites[0].specs[0].file = 'other.spec.ts' },
    report => { report.suites[0].specs[0].file = 'offline-compiled-pdf.spec.ts' },
    report => { report.suites[0].specs[0].title = report.suites[0].specs[1].title },
    report => { report.suites[0].specs[0].tests[0].projectName = 'blocked-worker-project' },
    report => { report.suites[0].specs[0].tests[0].results[0].status = 'skipped' },
    report => { report.errors.push({ message: 'setup failure' }) },
  ]) {
    const report = successfulReport(); mutate(report)
    assert.throws(() => verifyPwaReport(report))
  }
})
